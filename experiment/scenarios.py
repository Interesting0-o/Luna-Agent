def get_scenario_names() -> list[str]:
    """返回所有场景名称列表。"""
    return [s["name"] for s in SCENARIOS]


def get_scenario(name: str) -> dict:
    """按名称查找场景。"""
    for s in SCENARIOS:
        if s["name"] == name:
            return s
    raise KeyError(f"场景 '{name}' 未找到")


def get_scenarios_by_category(category: str) -> list[dict]:
    """按类别返回场景列表。"""
    return [s for s in SCENARIOS if s["category"] == category]


def get_scenario_summary() -> str:
    """返回场景摘要表格。"""
    lines = []
    lines.append(f"{'#':<4} {'场景':<16} {'类别':<12} {'描述':<40}")
    lines.append("-" * 80)
    for i, s in enumerate(SCENARIOS, 1):
        desc = s["description"][:38]
        lines.append(f"{i:<4} {s['name']:<16} {s['category']:<12} {desc:<40}")
    return "\n".join(lines)
